/**
 * Art authored as text is art that silently loses a character. Every sprite is checked on
 * import, so a mis-typed row fails the generator rather than shifting half a picture left.
 */
function check(name, size, rows) {
  if (rows.length !== size) throw new Error(`sprite ${name}: ${rows.length} rows, expected ${size}`)
  rows.forEach((row, y) => {
    if (row.length !== size) throw new Error(`sprite ${name} row ${y}: ${row.length} chars, expected ${size}`)
    for (const ch of row) {
      if (!(ch in C)) throw new Error(`sprite ${name} row ${y}: unknown colour '${ch}'`)
    }
  })
}

for (const [name, rows] of Object.entries(SPRITES_8)) check(name, 8, rows)
for (const [name, rows] of Object.entries(SPRITES_16)) check(name, 16, rows)
for (const [name, rows] of Object.entries(SPRITES_32)) check(name, 32, rows)

export function spriteColor(ch) {
  return C[ch] ?? null
}
