/**
 * Pixel-art sample: a dense sheet of small sprites, every one aligned to the 8x8 lattice.
 *
 * Alignment is the point. JPEG cuts the image into 8x8 blocks, so aligned sprites let a
 * slide select a block that holds exactly one 8x8 sprite, one quadrant of a 16x16, or one
 * sixteenth of a 32x32 — which makes the DCT and quantisation steps far easier to read
 * than a block straddling arbitrary detail.
 *
 * Three sizes, because they answer different questions. An 8x8 sprite *is* a block, so its
 * DCT is the sprite's own spectrum. A 16x16 or 32x32 sprite spans several blocks, so
 * neighbouring blocks hold related-but-different content — which is what makes the block
 * grid visible when quality drops.
 *
 * Sprites are deliberately mixed: flat single-colour shapes produce a DCT that is almost
 * all DC, while the multicolour ones spread energy into the higher coefficients.
 */

